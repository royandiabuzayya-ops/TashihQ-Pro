// Service Worker - TashihQ Pro
// Versi cache: naikkan angka ini setiap kali index.html/manifest/ikon diperbarui,
// agar pengguna lama mendapat versi baru (bukan versi cache basi).
const CACHE_VERSION = 'v1';
const CACHE_NAME = `tashihq-pro-${CACHE_VERSION}`;

// Berkas inti yang wajib bisa dibuka walau offline (app shell).
// Sesuaikan path index.html jika nama/lokasi filenya berbeda saat di-deploy.
const CORE_ASSETS = [
  './',
  './index.html',
  './manifest.webmanifest',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/icon-192-maskable.png',
  './icons/icon-512-maskable.png',
  './icons/apple-touch-icon.png',
  './icons/favicon-32.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(CORE_ASSETS))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((key) => key.startsWith('tashihq-pro-') && key !== CACHE_NAME)
          .map((key) => caches.delete(key))
      )
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);

  // Navigasi antar halaman (buka app / refresh) -> network-first, fallback ke shell offline
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          caches.open(CACHE_NAME).then((cache) => cache.put('./index.html', res.clone()));
          return res;
        })
        .catch(() => caches.match('./index.html'))
    );
    return;
  }

  // Aset dari domain sendiri (ikon, manifest, dll) -> cache-first
  if (url.origin === self.location.origin) {
    event.respondWith(
      caches.match(req).then((cached) => {
        if (cached) return cached;
        return fetch(req).then((res) => {
          const resClone = res.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(req, resClone));
          return res;
        });
      })
    );
    return;
  }

  // Aset CDN eksternal (Tailwind, FontAwesome, Chart.js, Google Fonts)
  // -> stale-while-revalidate: tampilkan cache dulu (jika ada) sambil update di background,
  //    supaya app tetap tampil rapi walau koneksi lambat/putus setelah pertama kali dibuka.
  event.respondWith(
    caches.match(req).then((cached) => {
      const networkFetch = fetch(req)
        .then((res) => {
          if (res && res.status === 200) {
            const resClone = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(req, resClone));
          }
          return res;
        })
        .catch(() => cached);
      return cached || networkFetch;
    })
  );
});
